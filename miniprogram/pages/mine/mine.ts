Page({
  ...shareConfig,

  data: {
    maps: [] as MineMap[],
    activeIndex: 0,
    activeName: '',
    activeFileID: '',
    activeImage: '',
    imageError: '',
    activeCoords: [] as Coord[],
    // 底部悬浮广告位高度（rpx），加载后实测并动态适配，避免遮挡内容或留白
    adReserve: 180,
    // 广告加载失败时隐藏广告位，避免空占位
    adHidden: false,
  },

  onLoad() {
    enableShareMenu();
    const maps = MAPS.map((m) => ({
      ...m,
      coords: parseCoords(m.raw),
      localPath: '',
    }));
    this.setData({ maps });
    this.selectMap(0);
  },

  selectMap(e: any) {
    const index = typeof e === 'number' ? e : e.currentTarget.dataset.index as number;
    const map = this.data.maps[index];
    if (!map) return;
    this.setData({
      activeIndex: index,
      activeName: map.name,
      activeFileID: map.fileID,
      activeImage: map.localPath || '',
      activeCoords: map.coords,
    });
    // 已下载过则不再重复请求
    if (map.localPath) return;
    // 免费环境存储为私有，前端无法直接换取临时地址，
    // 改为调用 getImageUrl 云函数（管理员身份）获取临时下载 URL
    wx.cloud.callFunction({
      name: 'getImageUrl',
      data: { fileList: [map.fileID] },
      success: (res: any) => {
        const result = res.result as { code: number; msg: string; list?: any[] };
        if (result.code !== 0 || !result.list || !result.list[0]) {
          console.error('[挖矿图片获取地址失败]', result);
          this.setData({ imageError: `图片地址获取失败：${result.msg}` });
          wx.showToast({ title: '图片加载失败', icon: 'none' });
          return;
        }
        const file = result.list[0];
        if (!file.tempFileURL) {
          console.error('[挖矿图片地址为空]', file);
          this.setData({ imageError: `图片地址为空：${file.status} ${file.errMsg}` });
          wx.showToast({ title: '图片加载失败', icon: 'none' });
          return;
        }
        const maps = this.data.maps;
        maps[index].localPath = file.tempFileURL;
        this.setData({ maps, activeImage: file.tempFileURL, imageError: '' });
      },
      fail: (err) => {
        console.error('[挖矿图片云函数调用失败]', err);
        this.setData({ imageError: `云函数调用失败：${err.errMsg}` });
        wx.showToast({ title: '图片加载失败', icon: 'none' });
      },
    });
  },

  copySide(e: any) {
    const value = e.currentTarget.dataset.value as number;
    wx.setClipboardData({
      data: String(value),
      success: () => wx.showToast({ title: `已复制 ${value}`, icon: 'none' }),
    });
  },

  // 原生模板广告加载成功：多次实测、以最终稳定高度为准（广告先占位后收缩），避免预留过高留白
  onAdLoad() {
    const measure = () => {
      wx.createSelectorQuery()
        .in(this)
        .select('.ad-card')
        .boundingClientRect((rect: WechatMiniprogram.BoundingClientRectCallbackResult | undefined) => {
          if (!rect || !rect.height) return;
          const winWidth = wx.getSystemInfoSync().windowWidth;
          const rpx = Math.ceil((rect.height * 750) / winWidth) + 24;
          this.setData({ adReserve: rpx });
        })
        .exec();
    };
    [200, 500, 1000, 1800].forEach((delay) => setTimeout(measure, delay));
  },

  // 广告加载失败：隐藏广告位并收回预留空间，避免空占位
  onAdError() {
    this.setData({ adReserve: 0, adHidden: true });
  },
});
