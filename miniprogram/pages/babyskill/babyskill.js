const DATA = { 被动: PASSIVE, 主动: ACTIVE };

Page({
  data: {
    skillTypeOptions: ['被动', '主动'],
    skillTypeIndex: 0, // 默认 被动
    charOptions: ['胆小', '勇猛', '忠诚', '谨慎', '精明'],
    charIndex: 0, // 默认 胆小
    columns: COLUMNS['被动'],
    rows: [],
    activeRow: -1, // 当前高亮行，-1 表示无
    showHelp: false,
    // 底部悬浮广告位高度（rpx），加载后实测并动态适配，避免遮挡内容或留白
    adReserve: 180,
    // 广告加载失败时隐藏广告位，避免空占位
    adHidden: false,
  },

  onLoad() {
    this.applyFilter();
  },

  // 根据 技能类型 + 宝宝性格 锁定对应概率数据
  applyFilter() {
    const { skillTypeIndex, charIndex, skillTypeOptions, charOptions } = this.data;
    const type = skillTypeOptions[skillTypeIndex];
    const char = charOptions[charIndex];
    const columns = COLUMNS[type];
    const rows = (DATA[type][char] || []).map((it, i) => ({ rid: i, ...it }));
    this.setData({ columns, rows, activeRow: -1 });
  },

  // 下拉切换技能类型（被动/主动）
  onSkillTypeChange(e) {
    const index = Number(e.detail.value);
    if (index === this.data.skillTypeIndex) return;
    this.setData({ skillTypeIndex: index });
    this.applyFilter();
  },

  // 下拉切换宝宝性格
  onCharChange(e) {
    const index = Number(e.detail.value);
    if (index === this.data.charIndex) return;
    this.setData({ charIndex: index });
    this.applyFilter();
  },

  // 点击行高亮（再次点击取消）
  onRowTap(e) {
    const index = Number(e.currentTarget.dataset.index);
    this.setData({ activeRow: this.data.activeRow === index ? -1 : index });
  },

  openHelp() {
    this.setData({ showHelp: true });
  },

  closeHelp() {
    this.setData({ showHelp: false });
  },

  // 阻止点击弹窗内容时关闭弹窗
  noop() {},

  // 原生模板广告加载成功：多次实测、以最终稳定高度为准（广告先占位后收缩），避免预留过高留白
  onAdLoad() {
    const measure = () => {
      wx.createSelectorQuery()
        .in(this)
        .select('.ad-card')
        .boundingClientRect((rect) => {
          if (!rect || !rect.height) return;
          const winWidth = wx.getSystemInfoSync().windowWidth;
          const rpx = Math.ceil((rect.height * 750) / winWidth) + 24;
          this.setData({ adReserve: rpx });
        })
        .exec();
    };
    [200, 500, 1000, 1800].forEach((delay) => setTimeout(measure, delay));
  },

  // 广告加载失败：隐藏广告位并收回预留空间，避免空占位
  onAdError() {
    this.setData({ adReserve: 0, adHidden: true });
  },
});
