Page({
  data: {
    options: [],
    selectedIndex: 0,
    rows: [],
    showHelp: false,
    // 底部悬浮广告位高度（rpx），加载后实测并动态适配，避免遮挡内容或留白
    adReserve: 180,
    // 广告加载失败时隐藏广告位，避免空占位
    adHidden: false,
  },

  onLoad() {
    const options = EQUIP_DATA.map((d) => d['装备位置']);
    this.setData({ options });
    this.buildRows(0);
  },

  // 下拉选择装备位置
  onSelectEquip(e) {
    const index = Number(e.detail.value);
    this.setData({ selectedIndex: index });
    this.buildRows(index);
  },

  // 按固定字段顺序生成展示行
  buildRows(index) {
    const item = EQUIP_DATA[index];
    if (!item) return;
    const rows = FIELDS.map((f) => ({ label: f.label, value: item[f.key] }));
    this.setData({ rows });
  },

  openHelp() {
    this.setData({ showHelp: true });
  },

  closeHelp() {
    this.setData({ showHelp: false });
  },

  // 阻止点击弹窗内容时关闭弹窗
  noop() {},

  // 原生模板广告加载成功：多次实测、以最终稳定高度为准（广告先占位后收缩），避免预留过高留白
  onAdLoad() {
    const measure = () => {
      wx.createSelectorQuery()
        .in(this)
        .select('.ad-card')
        .boundingClientRect((rect) => {
          if (!rect || !rect.height) return;
          const winWidth = wx.getSystemInfoSync().windowWidth;
          const rpx = Math.ceil((rect.height * 750) / winWidth) + 24;
          this.setData({ adReserve: rpx });
        })
        .exec();
    };
    [200, 500, 1000, 1800].forEach((delay) => setTimeout(measure, delay));
  },

  // 广告加载失败：隐藏广告位并收回预留空间，避免空占位
  onAdError() {
    this.setData({ adReserve: 0, adHidden: true });
  },
});
